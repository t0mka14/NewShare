interface SettingsComponent {
    val state: Value<State>

    fun onDeviceSelected(deviceId: String)
    fun onSiteTokenChanged(value: String)
    fun onLanguageSelected(language: String)
    fun onRefreshClicked()

    /** Re-enumerate the mic devices (same lookup as when the screen opens). */
    fun onRefreshDevicesClicked()

    /** The examiner picked a camera, or `null` for "Automatic (first available camera)"; saved at once. */
    fun onCameraSelected(deviceId: String?)

    /** Slider dragged (live); nothing is persisted or applied until [onMicGainChangeFinished]. */
    fun onMicGainChanged(value: Int)

    /** Slider released: the value becomes the local override and is set on the selected device. */
    fun onMicGainChangeFinished()

    /** Drop the local override; the config's default (if any for this device) is re-applied. */
    fun onMicGainReset()

    /** The examiner picked an indicator: it becomes the local override, even if equal to the config's. */
    fun onIndicatorTypeSelected(type: IndicatorType)

    /** Drop the indicator override; the config's `indicatorType` applies again. */
    fun onIndicatorTypeReset()

    data class State(
        val availableDevices: List<AudioInputDevice> = emptyList(),
        val selectedDeviceId: String? = null,
        /**
         * Why [selectedDeviceId] is selected: [MicChoice.Source.SAVED] when the examiner chose it,
         * else the default a session would use (config `defaultMicName`, or the system default) —
         * only preselected, not saved until the examiner picks a device. `null` without devices.
         */
        val micSource: MicChoice.Source? = null,
        /** Read-only: generated by [InstallationIdProvider], shown for support/tracing. */
        val installationId: String = "",
        val siteToken: String = "",
        val availableLanguages: List<String> = emptyList(),
        val selectedLanguage: String? = null,
        val refreshInProgress: Boolean = false,
        /** Localized-string key for the last refresh outcome (`settings.refresh.*` /
         * `error.config.*`); starts as the last failed refresh's key, else `null`. */
        val lastRefreshResultKey: String? = null,
        /** The last device check-in said this computer belongs to another site than the
         * entered token's (§13 decision 62); a note is shown under the refresh result. */
        val registeredToAnotherSite: Boolean = false,
        /**
         * Slider position (§13 decision 44): the level read from the selected device every time
         * the screen opens — so a change made in the OS sound panel shows up here — falling back
         * to the local override, else the config default, only while the device's level is not
         * readable; null until any of those is known.
         */
        val micGain: Int? = null,
        /** The persisted local override (`AppSettings.micGain`). */
        val micGainOverride: Int? = null,
        /** The config's `defaultMicGain`, only when the selected device matches `defaultMicName`. */
        val configMicGain: Int? = null,
        /** The selected device's level could be read through the OS — the slider is enabled. */
        val micGainControllable: Boolean = false,
        /** The read finished and returned no level — the device's level cannot be set. */
        val micGainUnavailable: Boolean = false,
        /** Cameras found by the last listing; empty until [camerasLoading] turns false. */
        val availableCameras: List<VideoInputDevice> = emptyList(),
        /** Listing cameras spawns a process, so it runs in the background (F-019). */
        val camerasLoading: Boolean = true,
        /** Saved `AppSettings.cameraDeviceId`; `null` = Automatic. May name a camera no longer listed. */
        val selectedCameraId: String? = null,
        /** The persisted local override (`AppSettings.indicatorType`, §13 decision 53). */
        val indicatorTypeOverride: IndicatorType? = null,
        /** The active config's `indicatorType` (its default when there is no config). */
        val configIndicatorType: IndicatorType = IndicatorType.CIRCLE,
    ) {
        /** What the next session's task screens will show. */
        val indicatorType: IndicatorType get() = indicatorTypeOverride ?: configIndicatorType
    }
}

/**
 * §3 Settings screen: mic device, microphone level, site token, language — persisted
 * immediately (write-through) via [AppSettingsRepository], never `Preferences` (§12). Refresh
 * delegates to [RefreshConfigurationUseCase] and maps its result to a localized string key (§7)
 * the UI resolves via `LocalizedStringProvider` — this component never holds display text.
 *
 * The level slider follows the legacy Settings screen: every time the screen opens it reads the
 * selected device's current level (asynchronously — the slider stays disabled until the read
 * completes, as the legacy `micSliderEnabled`) and shows *that*, so a level changed in the OS
 * sound panel is reflected; a released drag persists the value as the local override and sets it
 * on the device at once through [MicGainApplier]. Which value a session applies is decided in
 * the applier (override, else config), independent of what the device reads at the moment.
 */
class DefaultSettingsComponent(
    componentContext: ComponentContext,
    private val deviceProvider: AudioInputDeviceProvider,
    private val settingsRepository: AppSettingsRepository,
    private val configurationRepository: ConfigurationRepository,
    private val refreshConfigurationUseCase: RefreshConfigurationUseCase,
    private val micGainApplier: MicGainApplier,
    private val installationIdProvider: InstallationIdProvider,
    private val dispatchers: CoroutineDispatchers,
    private val videoDeviceProvider: VideoInputDeviceProvider,
    /** `DeviceCheckinUseCase.registeredToAnotherSite`; updated by the check-in after a refresh. */
    private val registeredToAnotherSite: StateFlow<Boolean> = MutableStateFlow(false),
) : SettingsComponent, ComponentContext by componentContext {

    private val scope = CoroutineScope(SupervisorJob() + dispatchers.default)

    /** Last level read from (or successfully written to) the selected device. */
    private var deviceLevel: Int? = null
    private var cameraListing: Job? = null

    private val _state = MutableValue(initialState())
    override val state: Value<SettingsComponent.State> = _state

    init {
        lifecycle.doOnDestroy { scope.cancel() }
        scope.launch(dispatchers.main) {
            registeredToAnotherSite.collect { _state.value = _state.value.copy(registeredToAnotherSite = it) }
        }
        scope.launch(dispatchers.main) {
            configurationRepository.activeConfig.collect { config ->
                _state.value = _state.value.copy(
                    availableLanguages = config?.languages.orEmpty(),
                    selectedLanguage = effectiveLanguage(settingsRepository.read()?.language, config),
                    configMicGain = configGainFor(config, selectedDevice()),
                    configIndicatorType = config?.indicatorType ?: IndicatorType.CIRCLE,
                ).withSliderPosition()
                reselectDefaultMic()
            }
        }
        readDeviceLevel()
        listCameras()
    }

    private fun initialState(): SettingsComponent.State {
        val saved = settingsRepository.read()
        val devices = deviceProvider.availableDevices()
        val config = configurationRepository.activeConfig.value
        // Preselect what a session would use (same chain as RootComponent); nothing is saved yet.
        val choice = MicChoice.choose(devices, saved?.micDeviceId, config?.defaultMicName)
        val selected = choice?.device
        return SettingsComponent.State(
            availableDevices = devices,
            selectedDeviceId = selected?.id ?: saved?.micDeviceId,
            micSource = choice?.source,
            installationId = installationIdProvider.get(),
            siteToken = saved?.siteToken.orEmpty(),
            selectedCameraId = saved?.cameraDeviceId,
            availableLanguages = config?.languages.orEmpty(),
            selectedLanguage = effectiveLanguage(saved?.language, config),
            // A failure from an earlier refresh (e.g. the startup one) is shown on arrival.
            lastRefreshResultKey = refreshConfigurationUseCase.lastError.value?.messageKey()
                ?: OFFLINE_KEY.takeIf { refreshConfigurationUseCase.usingCachedConfig.value },
            micGainOverride = saved?.micGain?.coerceIn(MIC_GAIN_RANGE),
            configMicGain = configGainFor(config, selected),
            indicatorTypeOverride = saved?.indicatorType,
            configIndicatorType = config?.indicatorType ?: IndicatorType.CIRCLE,
        ).withSliderPosition()
    }

    override fun onDeviceSelected(deviceId: String) {
        val device = _state.value.availableDevices.firstOrNull { it.id == deviceId }
        _state.value = _state.value.copy(
            selectedDeviceId = deviceId,
            micSource = MicChoice.Source.SAVED,
            configMicGain = configGainFor(configurationRepository.activeConfig.value, device),
        )
        persist()
        readDeviceLevel()
    }

    override fun onSiteTokenChanged(value: String) {
        _state.value = _state.value.copy(siteToken = value)
        persist()
    }

    override fun onLanguageSelected(language: String) {
        _state.value = _state.value.copy(selectedLanguage = language)
        persist()
    }

    override fun onRefreshClicked() {
        _state.value = _state.value.copy(refreshInProgress = true, lastRefreshResultKey = null)
        scope.launch(dispatchers.main) {
            val resultKey = when (val result = refreshConfigurationUseCase.refresh()) {
                // The check-in ran inside refresh(): one status, not "OK" above an other-site warning.
                is RefreshConfigurationUseCase.Result.Success ->
                    if (registeredToAnotherSite.value) OTHER_SITE_KEY else "settings.refresh.success"
                is RefreshConfigurationUseCase.Result.OfflineUsingCache -> OFFLINE_KEY
                is RefreshConfigurationUseCase.Result.Failed -> result.error.messageKey()
            }
            _state.value = _state.value.copy(refreshInProgress = false, lastRefreshResultKey = resultKey)
        }
    }

    override fun onRefreshDevicesClicked() {
        val devices = deviceProvider.availableDevices()
        val selected = devices.firstOrNull { it.id == _state.value.selectedDeviceId }
        _state.value = _state.value.copy(
            availableDevices = devices,
            configMicGain = configGainFor(configurationRepository.activeConfig.value, selected),
        )
        readDeviceLevel()
        reselectDefaultMic()
        listCameras()
    }

    override fun onCameraSelected(deviceId: String?) {
        _state.value = _state.value.copy(selectedCameraId = deviceId)
        settingsRepository.write((settingsRepository.read() ?: AppSettings()).copy(cameraDeviceId = deviceId))
    }

    /** Enumeration blocks on ffmpeg: never on the main thread, never when the screen is built. */
    private fun listCameras() {
        cameraListing?.cancel()
        _state.value = _state.value.copy(camerasLoading = true)
        cameraListing = scope.launch(dispatchers.main) {
            val cameras = withContext(dispatchers.io) { videoDeviceProvider.availableDevices() }
            _state.value = _state.value.copy(availableCameras = cameras, camerasLoading = false)
        }
    }

    override fun onMicGainChanged(value: Int) {
        _state.value = _state.value.copy(micGain = value.coerceIn(MIC_GAIN_RANGE))
    }

    override fun onMicGainChangeFinished() {
        val value = _state.value.micGain ?: return
        _state.value = _state.value.copy(micGainOverride = value)
        persist()
        val device = selectedDevice() ?: return
        scope.launch(dispatchers.main) {
            if (micGainApplier.set(device, value) is GainApplyResult.Applied) deviceLevel = value
        }
    }

    override fun onMicGainReset() {
        _state.value = _state.value.copy(micGainOverride = null).withSliderPosition()
        persist()
        val device = selectedDevice() ?: return
        val configured = _state.value.configMicGain ?: return
        scope.launch(dispatchers.main) {
            if (micGainApplier.set(device, configured) is GainApplyResult.Applied) {
                deviceLevel = configured
                _state.value = _state.value.withSliderPosition()
            }
        }
    }

    override fun onIndicatorTypeSelected(type: IndicatorType) {
        _state.value = _state.value.copy(indicatorTypeOverride = type)
        persist()
    }

    override fun onIndicatorTypeReset() {
        _state.value = _state.value.copy(indicatorTypeOverride = null)
        persist()
    }

    /** The saved language, or the config's default when the config doesn't offer it (mirrors
     *  `RootComponent`'s rule, so the dropdown shows the language the app actually uses). */
    private fun effectiveLanguage(saved: String?, config: RemoteConfig?): String? {
        val offered = config?.languages.orEmpty()
        return if (saved != null && (offered.isEmpty() || saved in offered)) saved else config?.defaultLanguage ?: saved
    }

    /** While the microphone is only a preselected default, follow device-list and config changes. */
    private fun reselectDefaultMic() {
        if (_state.value.micSource == MicChoice.Source.SAVED) return
        val config = configurationRepository.activeConfig.value
        val choice = MicChoice.choose(_state.value.availableDevices, settingsRepository.read()?.micDeviceId, config?.defaultMicName)
        val deviceId = choice?.device?.id ?: _state.value.selectedDeviceId
        val changed = deviceId != _state.value.selectedDeviceId
        _state.value = _state.value.copy(
            selectedDeviceId = deviceId,
            micSource = choice?.source,
            configMicGain = configGainFor(config, choice?.device),
        )
        if (changed) readDeviceLevel()
    }

    private fun selectedDevice(): AudioInputDevice? =
        _state.value.availableDevices.firstOrNull { it.id == _state.value.selectedDeviceId }

    /** The config's level, but only for the device it names (the applier's rule, §13/44). */
    private fun configGainFor(config: RemoteConfig?, device: AudioInputDevice?): Int? {
        val gain = config?.defaultMicGain ?: return null
        if (device == null || !MicNames.matches(config.defaultMicName, device)) return null
        return gain.coerceIn(MIC_GAIN_RANGE)
    }

    private fun SettingsComponent.State.withSliderPosition(): SettingsComponent.State =
        copy(micGain = deviceLevel ?: micGainOverride ?: configMicGain)

    /** Legacy `findMicGain`: disable the slider, read the device's level off the UI thread, re-enable. */
    private fun readDeviceLevel() {
        deviceLevel = null
        _state.value = _state.value.copy(micGainControllable = false, micGainUnavailable = false).withSliderPosition()
        val device = selectedDevice() ?: return
        scope.launch(dispatchers.main) {
            val level = micGainApplier.read(device)
            if (selectedDevice()?.id != device.id) return@launch // the examiner moved on
            deviceLevel = level
            _state.value = _state.value.copy(micGainControllable = level != null, micGainUnavailable = level == null).withSliderPosition()
        }
    }

    private fun persist() {
        val current = _state.value
        // Merge onto the saved settings: `cameraDeviceId` is owned by the camera flow and
        // `installationId` by InstallationIdProvider, not this screen.
        val saved = settingsRepository.read() ?: AppSettings()
        settingsRepository.write(
            saved.copy(
                // A preselected default is not the examiner's choice: leave what was saved alone.
                micDeviceId = if (current.micSource == MicChoice.Source.SAVED) current.selectedDeviceId else saved.micDeviceId,
                siteToken = current.siteToken.trim().ifBlank { null },
                language = current.selectedLanguage,
                micGain = current.micGainOverride,
                indicatorType = current.indicatorTypeOverride,
            ),
        )
    }

    private companion object {
        /** The server was unreachable and the cached config stays active (§6.1 pt 4). */
        const val OFFLINE_KEY = "settings.refresh.offline"

        /** The device check-in says this computer belongs to another site; the fetched config was not applied (F-041). */
        const val OTHER_SITE_KEY = "settings.refresh.otherSite"
    }
}
